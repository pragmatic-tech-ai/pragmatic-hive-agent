import { SigningKeyPair } from '@pragmatic-tech-ai/pragmatic-hive-protocol'
import type { IHiveKube } from '../kube/hive-kube.js'

/** The identity Secret exists but holds no usable key (edited by hand?): never silently replaced. */
export class HiveIdentityUnusableError extends Error
{
    private static readonly ErrorName = 'HiveIdentityUnusableError'
    private static readonly Text = 'the Secret pragmatic-hive-identity holds no usable Ed25519 key (hive-key.pem); remove it to enrol again with a new key'

    public constructor()
    {
        super(HiveIdentityUnusableError.Text)
        this.name = HiveIdentityUnusableError.ErrorName
    }
}

/**
 * The hive's own Ed25519 key (C3.3): generated by the agent inside the cluster the first time it starts connected and
 * kept in the Secret `pragmatic-hive-identity` (PKCS#8 PEM under `hive-key.pem`), never replaced, so a restart (even
 * one mid-enrolment) signs with the same key. The private half never leaves the cluster and appears in no log line or
 * answer; the platform records only the public half.
 */
export class HiveIdentity
{
    public static readonly SecretName = 'pragmatic-hive-identity'
    public static readonly KeyName = 'hive-key.pem'
    /** The key a hive key rotation (C3.4) announced and the platform has not acknowledged yet. */
    public static readonly PendingKeyName = 'hive-key-next.pem'
    /** managed-by: the agent's admission policy (C3.4) admits only objects it, the console or the chart manages. */
    public static readonly Labels: Readonly<Record<string, string>> = { 'app.kubernetes.io/part-of': 'pragmatic-engine', 'app.kubernetes.io/component': 'pragmatic-hive-agent', 'app.kubernetes.io/managed-by': 'pragmatic-hive-agent' }

    private constructor()
    {
    }

    public static async LoadOrCreate(kube: IHiveKube, namespace: string): Promise<SigningKeyPair>
    {
        const H = HiveIdentity
        const existing = await H.Load(kube, namespace)
        if (existing !== undefined)
        {
            return existing
        }
        const key = SigningKeyPair.Generate()
        if (await kube.CreateSecret(namespace, H.SecretName, { [H.KeyName]: key.PrivatePem() }, H.Labels))
        {
            return key
        }
        // Another start created it first: use that one.
        const raced = await H.Load(kube, namespace)
        if (raced === undefined)
        {
            throw new HiveIdentityUnusableError()
        }
        return raced
    }

    /** The pending next key (a rotation announced, not acknowledged), if any. */
    public static async Pending(kube: IHiveKube, namespace: string): Promise<SigningKeyPair | undefined>
    {
        const pem = (await kube.GetSecretData(namespace, HiveIdentity.SecretName))?.[HiveIdentity.PendingKeyName]
        if (pem === undefined)
        {
            return undefined
        }
        try
        {
            return SigningKeyPair.FromPrivatePem(pem)
        }
        catch
        {
            return undefined
        }
    }

    /** Keeps `next` beside the current key before it is announced, so a restart mid-rotation still holds it. */
    public static async WritePending(kube: IHiveKube, namespace: string, current: SigningKeyPair, next: SigningKeyPair): Promise<void>
    {
        const H = HiveIdentity
        await kube.ReplaceSecret(namespace, H.SecretName, { [H.KeyName]: current.PrivatePem(), [H.PendingKeyName]: next.PrivatePem() }, H.Labels)
    }

    /** Makes `key` the hive key (the platform acknowledged it) and drops any pending one. */
    public static async Adopt(kube: IHiveKube, namespace: string, key: SigningKeyPair): Promise<void>
    {
        const H = HiveIdentity
        await kube.ReplaceSecret(namespace, H.SecretName, { [H.KeyName]: key.PrivatePem() }, H.Labels)
    }

    private static async Load(kube: IHiveKube, namespace: string): Promise<SigningKeyPair | undefined>
    {
        const data = await kube.GetSecretData(namespace, HiveIdentity.SecretName)
        if (data === undefined)
        {
            return undefined
        }
        const pem = data[HiveIdentity.KeyName]
        if (pem === undefined)
        {
            throw new HiveIdentityUnusableError()
        }
        try
        {
            return SigningKeyPair.FromPrivatePem(pem)
        }
        catch
        {
            throw new HiveIdentityUnusableError()
        }
    }
}
